// #397 表行数的显示口径：唯一来源（组件与测试共用）。
//
// 为什么单列一个模块：`? = 行数未知` 这个判断很容易被顺手改回去
// （写成 `n ?? 0`、或者把 null 当 0 显示）。本仓 #384/#397 两次都是
// 「以为修好了、实际那段判断压根没跑到」。让组件 import 它、测试直接钉它，
// 就不必去 .vue 里抠字符串。

/**
 * 行数 → 显示文本。
 * `null` / `undefined` = 后端没数出来（COUNT 失败），显示 `?`。
 *
 * **绝不能显示 0**：运维数据库页是「库还在不在」的体检页，
 * 0 在这一页只有一个读法——数据没了；而 COUNT 失败的原因常常只是
 * 库被锁 / 连接池打满 / 那张表正被长事务占着，数据好好在那儿。
 * 显示 0 会让用户去翻备份、想去重建。
 *
 * 真正的空表（数出来了 = 0）仍然显示 0——别把这条也一起改掉，
 * 否则就变成「永远数不出行数」。
 */
export function fmtRowCount(n: number | null | undefined): string {
  if (n === undefined || n === null) return '?'
  return n.toLocaleString()
}
