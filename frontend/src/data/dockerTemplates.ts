// Docker 应用模板库 —— 预置常用应用，一键填充创建向导。
// 对标飞牛/绿联/极空间 NAS 应用商店：小白用户选模板 → 微调 → 创建。

export interface DockerTemplatePort {
  host: number
  container: number
  protocol: 'tcp' | 'udp'
}

export interface DockerTemplateVolume {
  host: string
  container: string
  mode: 'rw' | 'ro'
}

export interface DockerTemplateEnv {
  key: string
  value: string
}

export type DockerTemplateCategory =
  '下载工具' | '媒体影音' | '文件管理' | '图片相册' | '笔记知识' | '开发工具' | '系统工具' | '容器管理' | '智能家居'

export interface DockerTemplate {
  id: string
  name: string
  category: DockerTemplateCategory
  icon: string
  color: string
  description: string
  image: string
  ports: DockerTemplatePort[]
  volumes: DockerTemplateVolume[]
  env: DockerTemplateEnv[]
  networkMode: string
  privileged: boolean
  restartPolicy: string
  cpuLimit: number
  memoryLimitMB: number
}

function D(path: string): string {
  return '/opt/docker/' + path
}

