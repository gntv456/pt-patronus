// scripts/gen-site-index.mjs — 阶段 4：把 definitions/*.yaml 下沉为编译期索引
//
// 生成 backend/internal/site/zz_defs_index.go（zz_ 前缀已被 check_file_length.sh 排除）。
// MatchByURL 走该表做 O(1) host 匹配，避免每次遍历 307 个定义 + 持锁。
// 零 Go 工具链依赖：只用 Node 内置模块，可由 make gen-site-index / go:generate 调用。
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join, resolve, basename, extname } from 'node:path'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const defsDir = join(root, 'backend', 'definitions')
const outFile = join(root, 'backend', 'internal', 'site', 'zz_defs_index.go')
if (!existsSync(defsDir)) { console.error('definitions 目录不存在:', defsDir); process.exit(1) }

function hostOf(s) {
  let v = String(s).trim().replace(/^['"]|['"]$/g, '')
  if (!v || v.startsWith('#')) return ''
  try { return new URL(v.includes('://') ? v : 'https://' + v).hostname.toLowerCase() } catch { return '' }
}

const hosts = new Map()
const ids = new Set()
for (const file of readdirSync(defsDir)) {
  if (!/\.ya?ml$/.test(file)) continue
  const text = readFileSync(join(defsDir, file), 'utf8')
  const lines = text.split(/\r?\n/)
  let id = basename(file, extname(file))
  const m = text.match(/^id:\s*([^\s#]+)/m)
  if (m) id = m[1].replace(/^['"]|['"]$/g, '')
  ids.add(id)
  let section = ''
  for (const line of lines) {
    const sec = line.match(/^([a-zA-Z_][a-zA-Z0-9_]*):\s*(.*)$/)
    if (sec) { section = sec[1]; if (/^https?:|^['"]?https?:/.test(sec[2])) { const h = hostOf(sec[2]); if (h && !hosts.has(h)) hosts.set(h, id) } continue }
    if (!/^(urls|legacy_urls|legacyUrls|domains|base_url|url)$/.test(section)) continue
    const item = line.match(/^\s*-\s*([^#]+?)\s*$/)
    if (!item) continue
    const h = hostOf(item[1])
    if (h && !hosts.has(h)) hosts.set(h, id)
  }
}

const idList = [...ids].sort()
const hostList = [...hosts.keys()].sort()
const q = (s) => JSON.stringify(s)
const out = [
  '// Code generated by scripts/gen-site-index.mjs; DO NOT EDIT.',
  '',
  'package site',
  '',
  `// BuiltinDefinitionHosts: ${hostList.length} hosts from ${idList.length} builtin definitions.`,
  '// 编译期生成，供 MatchByURL 快速路径使用；远端热加载定义仍走运行时遍历。',
  'var BuiltinDefinitionHosts = map[string]string{',
  ...hostList.map((h) => `\t${q(h)}: ${q(hosts.get(h))},`),
  '}',
  '',
  '// BuiltinDefinitionIDs 为内置站点定义 ID 全集（启动诊断/完整性校验用）。',
  'var BuiltinDefinitionIDs = []string{',
  ...idList.map((id) => `\t${q(id)},`),
  '}',
  '',
].join('\n')
writeFileSync(outFile, out)
console.log(`[gen-site-index] ${idList.length} defs, ${hostList.length} hosts -> ${outFile}`)